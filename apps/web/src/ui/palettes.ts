/** Color tokens consumed by the stylesheets as CSS custom properties. */
export interface Tokens {
  paper: string;
  surface: string;
  ink: string;
  muted: string;
  rule: string;
  ai: string;
  onAi: string;
  shu: string;
  onShu: string;
  ok: string;
  warn: string;
  /** One identity color per part of the routine: review, lesson, writing, listening. */
  srs: string;
  les: string;
  out: string;
  lis: string;
}

export interface Palette {
  id: string;
  name: string;
  jp: string;
  description: string;
  light: Tokens;
  dark: Tokens;
}

